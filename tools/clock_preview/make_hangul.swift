// Renders the Hangul word-clock letters into 1-bit bitmaps for the firmware
// (firmware/ESP32_Display/hangul_grid.h). Run: swift tools/clock_preview/make_hangul.swift
import CoreText
import CoreGraphics
import Foundation

let grid = ["열한두세네다", "섯여섯일곱여", "덟아홉시이삼", "사오십오분정", "오전오후각♥"]
let size = 24, fontSize: CGFloat = 21
let font = CTFontCreateWithName("AppleSDGothicNeo-Bold" as CFString, fontSize, nil)
var out = "// Generated by tools/clock_preview/make_hangul.swift from Apple SD Gothic Neo Bold. Do not edit.\n"
out += "// Hangul word clock: \(grid.count) rows x 6 letters, each \(size)x\(size) px, 1 bit per pixel, rows MSB first.\n"
out += "// " + grid.joined(separator: " / ") + "\n"
out += "const int WORD_ROWS=\(grid.count), WORD_COLS=6, WORD_PX=\(size);\n"
out += "const uint8_t WORD_GLYPHS[\(grid.count * 6)][\(size * size / 8)] PROGMEM={\n"
for row in grid {
    for ch in row {
        let space = CGColorSpaceCreateDeviceGray()
        let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: size,
                            space: space, bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        ctx.setFillColor(gray: 0, alpha: 1); ctx.fill(CGRect(x: 0, y: 0, width: size, height: size))
        let attr = NSAttributedString(string: String(ch), attributes: [
            NSAttributedString.Key(kCTFontAttributeName as String): font,
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(gray: 1, alpha: 1)])
        let line = CTLineCreateWithAttributedString(attr)
        let b = CTLineGetBoundsWithOptions(line, .useGlyphPathBounds)
        ctx.textPosition = CGPoint(x: (CGFloat(size) - b.width) / 2 - b.minX, y: (CGFloat(size) - b.height) / 2 - b.minY)
        CTLineDraw(line, ctx)
        let px = ctx.data!.bindMemory(to: UInt8.self, capacity: size * size)
        var bytes: [String] = []
        for y in 0..<size {
            for xb in 0..<(size / 8) {
                var v: UInt8 = 0
                for bit in 0..<8 where px[y * size + xb * 8 + bit] >= 110 { v |= 0x80 >> UInt8(bit) }
                bytes.append(String(format: "0x%02X", v))
            }
        }
        // Bitmap memory is top row first (drawing coordinates start at the bottom).
        out += "  {" + bytes.joined(separator: ",") + "},   // \(ch)\n"
    }
}
out += "};\n"
try! out.write(toFile: "firmware/ESP32_Display/hangul_grid.h", atomically: true, encoding: .utf8)
print("wrote \(grid.count * 6) letters")
